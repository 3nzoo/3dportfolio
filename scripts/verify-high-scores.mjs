import assert from 'node:assert/strict';
import { createHighScoreClient } from '../src/game/high-scores.js';
import { createRecordStore } from '../src/game/play-round.js';

const settings = { url: 'https://example.supabase.co', key: 'sb_publishable_test' };
const row = { player_name: 'Enzo', score: 480, country_code: 'PH' };
const shots = Array.from({ length: 10 }, () => ({ pocketId: 'experiences', bounces: 20, points: 999999 }));
const submissionId = '00000000-0000-4000-8000-000000000001';
let requests = [];
const client = createHighScoreClient(settings, async (url, options) => {
  requests.push({ url, options });
  return Response.json(options.method === 'POST' ? { saved: true, best: { player_name: 'Visitor', score: 600, country_code: 'JP' } } : [row]);
});
assert.equal(client.configured, true);
assert.deepEqual(await client.loadBest(), { name: 'Enzo', score: 480, country: 'PH' });
assert.match(requests[0].url, /is_visible=eq.true/);
assert.match(requests[0].url, /order=score.desc,created_at.asc,id.asc/);
assert.equal(requests[0].options.headers.Authorization, undefined, 'Publishable keys must not be sent as JWTs.');
assert.equal(requests[0].options.cache, 'no-store');
const submitted = await client.submit({ submissionId, name: ' Visitor ', country: 'JP', shots });
assert.equal(submitted.saved, true);
assert.equal(submitted.best.score, 600);
const body = JSON.parse(requests[1].options.body);
assert.equal(body.p_player_name, 'Visitor');
assert.equal(body.p_submission_id, submissionId);
assert.deepEqual(body.p_shots[0], { pocket_id: 'experiences', bounces: 20 }, 'The server must calculate points from shots, not a supplied total.');
assert.equal(body.score, undefined);
assert.equal(createHighScoreClient({ ...settings, key: 'sb_secret_forbidden' }).configured, false);
assert.equal(createHighScoreClient({ ...settings, url: 'http://example.supabase.co' }).configured, false);
await assert.rejects(client.submit({ submissionId, name: 'Visitor', country: 'JP', shots: shots.slice(1) }), /ten balls/);
await assert.rejects(client.submit({ submissionId, name: 'Visitor', country: 'XX', shots }), /country/);
await assert.rejects(client.submit({ submissionId, name: 'Visitor', country: 'JP', shots: shots.map(shot => ({ ...shot, bounces: -1 })) }), /ten balls/);
const empty = createHighScoreClient(settings, async () => Response.json([]));
assert.equal(await empty.loadBest(), null);
const unknownCountry = createHighScoreClient(settings, async () => Response.json([{ ...row, country_code: null }]));
assert.equal((await unknownCountry.loadBest()).country, null);
const failedSave = createHighScoreClient(settings, async () => Response.json({ message: 'Unavailable' }, { status: 500 }));
await assert.rejects(failedSave.submit({ submissionId, name: 'Visitor', country: 'JP', shots }), /unavailable/);
const missingMigration = createHighScoreClient(settings, async () => Response.json({ code: 'PGRST202' }, { status: 404 }));
await assert.rejects(missingMigration.submit({ submissionId, name: 'Visitor', country: 'JP', shots }), /migration/);
const limited = createHighScoreClient(settings, async () => Response.json({}, { status: 429 }));
await assert.rejects(limited.submit({ submissionId, name: 'Visitor', country: 'JP', shots }), /one minute/);
const raced = createHighScoreClient(settings, async () => Response.json({ saved: false, best: { ...row, score: 900 } }));
assert.equal((await raced.submit({ submissionId, name: 'Visitor', country: 'JP', shots })).saved, false);
const timeout = createHighScoreClient({ ...settings, timeoutMs: 5 }, async (_url, { signal }) => new Promise((_resolve, reject) => {
  signal.addEventListener('abort', () => reject(new DOMException('Aborted', 'AbortError')));
}));
await assert.rejects(timeout.loadBest(), /unavailable/);
let cached = JSON.stringify({ name: 'Old local record', score: 9999, country: 'PH' });
const store = createRecordStore({ getItem: () => cached, setItem: (_key, value) => { cached = value; } });
assert.equal(store.best.score, 9999);
assert.equal(store.replace({ name: 'Enzo', score: 480, country: 'PH' }), true);
assert.equal(store.best.score, 480, 'A stale local record must not override the shared record.');
assert.equal(JSON.parse(cached).score, 480);
assert.equal(store.replace({ name: 'Invalid', score: -1, country: 'PH' }), false);
console.log('High-score checks passed: shared loading, validated submissions, failures, retry IDs, timeouts, and authoritative shared records.');
