import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadRapier } from './lib/load-rapier.mjs';
import { createBoardPins } from '../src/game/board-settings.js';
import { createGamePhysics, FIXED_TIMESTEP, POCKETS, routeConfiguration } from '../src/game/physics.js';

const repository = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const temporaryDirectory = await mkdtemp(join(tmpdir(), 'florenzo-recordings-'));
try {
  const RAPIER = await loadRapier(repository, temporaryDirectory);
  const pins = createBoardPins();
  const candidates = Object.fromEntries(POCKETS.map(pocket => [pocket.id, []]));
  // Search only at build time. Every probe uses a fresh world, just like a real
  // launch, and records actual collision order rather than drawing a fake path.
  for (let index = 0; index <= 864; index++) {
    const power = 0.5 + index / 64;
    let result, ticks = 0;
    const pinSequence = [], samples = [];
    const probe = createGamePhysics(RAPIER, pins, landed => { result = landed; }, hit => { pinSequence.push(hit.index); });
    try {
      probe.launch(power);
      while (probe.inFlight && ticks < 900) {
        probe.step(FIXED_TIMESTEP); ticks++;
        if (probe.phase === 'field' && ticks % 6 === 0) {
          const { x, y } = probe.position;
          samples.push([Number(x.toFixed(4)), Number(y.toFixed(4))]);
        }
      }
    } finally { probe.dispose(); }
    if (result && result.bounces >= 5 && ticks <= 600) candidates[result.pocket.id].push({
      power, bounces: result.bounces, pinSequence, samples,
      seconds: Number((ticks * FIXED_TIMESTEP).toFixed(4)), landingX: result.x,
    });
  }
  const destinations = {};
  for (const pocket of POCKETS) {
    // Keep genuinely different pin sequences. Favor lively, high-bounce paths,
    // then spread their speeds so the variation is visible from the launch.
    const unique = new Map();
    for (const route of candidates[pocket.id].sort((a, b) => b.bounces - a.bounces || a.seconds - b.seconds)) {
      const key = route.pinSequence.join(',');
      if (!unique.has(key)) unique.set(key, route);
    }
    const routes = [...unique.values()];
    if (routes.length < 10) throw new Error(`${pocket.label} has only ${routes.length} distinct routes with five or more bounces.`);
    const selected = [routes.shift()];
    while (selected.length < 10) {
      routes.sort((a, b) => {
        const score = route => route.bounces + Math.min(...selected.map(other => Math.abs(other.power - route.power))) * 2;
        return score(b) - score(a) || a.seconds - b.seconds;
      });
      selected.push(routes.shift());
    }
    destinations[pocket.id] = selected.sort((a, b) => a.power - b.power).map((route, index) => ({
      id: `${pocket.id}-${index + 1}`, ...route,
    }));
  }
  const catalog = { rapierVersion: RAPIER.version(), configuration: routeConfiguration(pins), destinations };
  await writeFile(join(repository, 'src/game/recorded-routes.js'),
    `// Generated by npm run record:paths. Do not edit by hand.\nexport const RECORDED_ROUTES = ${JSON.stringify(catalog, null, 2)};\n`);
  console.log(JSON.stringify(Object.fromEntries(POCKETS.map(pocket => [pocket.id, {
    candidates: candidates[pocket.id].length,
    recorded: destinations[pocket.id].length,
    bounceRange: [Math.min(...destinations[pocket.id].map(route => route.bounces)), Math.max(...destinations[pocket.id].map(route => route.bounces))],
    powerRange: [destinations[pocket.id][0].power, destinations[pocket.id].at(-1).power],
  }])), null, 2));
} finally { await rm(temporaryDirectory, { recursive: true, force: true }); }
